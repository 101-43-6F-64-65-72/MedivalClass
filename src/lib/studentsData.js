export function getStudentsByClass(className) {
  if (!className) return [];
  const normalized = className.trim().toUpperCase().replace(/\s+/g, ' ');
  return STUDENTS_DATA.filter((s) => s.class.toUpperCase() === normalized);
}

export function findStudentByNis(nis) {
  if (!nis) return null;
  return STUDENTS_DATA.find((s) => String(s.nis).trim() === String(nis).trim()) || null;
}

export function findStudentByName(name) {
  if (!name) return null;
  const lower = name.trim().toLowerCase();
  return STUDENTS_DATA.find((s) => s.name.toLowerCase().includes(lower)) || null;
}
